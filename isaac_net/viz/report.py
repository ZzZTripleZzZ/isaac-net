"""Self-contained HTML reports (inline base64 PNGs, no external files).

    from isaac_net.viz.report import from_records
    from_records(["runs/l2", "runs/l0"], "report.html")        # RecorderLoop directories, or one parent directory

from_records writes a per-run summary table (envs, robots, steps, delivered messages per env-second, loss, delay p50
/ p95, AoI p95, PRB utilization, first-transmission BLER, energy), the delay and AoI CDFs of every run, delivered vs
offered throughput, and the per-cell PRB utilization heatmap of every run that has one. The helpers (figure to
<img>, table to HTML, page skeleton) are shared with `isaac-net-bench report --html`.
"""
