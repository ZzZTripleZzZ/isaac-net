"""Background users: UEs that are not robots but share every cell with them and consume its resources.

    from isaac_net.core import NRConfig, TrafficModel, make_engine
    from isaac_net.core.background import BackgroundConfig
    bg = BackgroundConfig(n_background=8, traffic=(TrafficModel.video(fps=30, mean_frame_bytes=4000),),
                          mobility="random_waypoint", speed_mps=1.5)
    net = make_engine("L2", E, R, dev, NRConfig(background=bg))      # wrapped automatically

`n_background` UEs per cell. Their positions are drawn uniformly at every reset (in the arena, or around their own
gNB with several cells) or taken from `positions_m`, and they stay put or move by random waypoint. Their traffic
comes from the traffic models of core/traffic.py (periodic, bursty, video). The policy neither controls nor observes
them: every per-robot output keeps its shape [E, R, ...]. Two implementations, one per kind of level:

1. Ghost robots (level "L2", the NR engine). The engine runs with R + R_bg robots, where R_bg = n_background * C.
   Rows R .. R + R_bg - 1 are the background UEs: the traffic models of `traffic` run on them inside the step, the
   engine's radio sees their poses (or the path loss of their positions when the input is an SNR or a path gain),
   and they compete for RBGs in the PF scheduler, take HARQ processes, interfere with other cells and hand over like
   any robot. The user's traffic models are restricted to rows 0 .. R - 1, and every input [E, R, ...] is padded
   for the ghost rows (no policy messages, no triggers). Every output [E, R_total, ...] is sliced back to [E, R, ...].
2. Offered load (the prototype levels "L1" and "L2-legacy", every backend). The frozen schedulers have no room for
   extra rows with generated traffic, so the background enters as a fixed offered load. Each background UE u offers
   lambda_u bytes per control step (the mean rate of its traffic models) and needs the share
   rho_u = lambda_u / (K * S * BYTES_PER_SE * se(snr_u)) of its cell's RBG-slots, where se is the legacy spectral
   efficiency at its full-power SNR on one subband (the legacy path loss of its distance to the nearest gNB, no
   shadowing or fading), K the UL slots per step and S = 5 subbands. A cell's background load is
   rho_c = min(max_util, sum of rho_u over its UEs). The approximation: the background takes the share rho_c of
   every resource the robots of that cell are granted. It is applied by scaling the size of every robot message by
   1 / (1 - rho_c) of the robot's serving cell when the message is enqueued (so each granted RBG carries 1 - rho_c
   of the robot's bytes). For L1 (equal share among backlogged robots, byte service independent of the backlog)
   this is exactly a capacity reduction by 1 - rho_c. For L2-legacy it keeps the PF, SR/BSR, HARQ and fading
   dynamics and slows the robots' queues by the same factor; it does not model the background's own burstiness or
   PF competition. The load is re-evaluated each step from the background positions, and a message keeps the
   factor it was enqueued with. queue_bytes is reported in the robots' own bytes.

Step dict keys added (per step, [E, C]; C = number of cells):
  bg_n                  background UEs attached to the cell (ghosts: serving cell; load: nearest gNB)
  bg_offered_bytes      bytes the background offered this step (ghosts: accepted generated bytes on the air; load:
                        the mean offered bytes lambda)
  bg_util               share of the cell's UL resources the background used (ghosts: PRB-slots of background
                        transmissions over the PRB-slots of the step's UL data slots; load: rho_c)
  bg_delivered_bytes, bg_lost_bytes, bg_queue_bytes   ghosts only: bytes of background messages delivered, timed out
                        or dropped this step, and queued at its end (byte conservation:
                        sum offered = sum delivered + sum lost + queued)
The background positions are `bg_pos` [E, R_bg, 2] (after the step).

Randomness: placement and waypoints come from the wrapper's own counter-based streams (proto/rng.py), keyed by
(seed, env id, episode), so a partial reset redraws exactly those envs and a shard of a larger batch draws the same
numbers for an env as the unsharded engine. With n_background = 0 make_engine returns the plain engine.
"""
from __future__ import annotations

import math
from dataclasses import dataclass

import torch

from .proto import netsim as _ns
from .proto.rng import RESET, STEP, CounterRNG, mix32
from .queues import env_mask
